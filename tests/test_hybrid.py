class TestHybridRescue:
    """Verify the core hybrid value proposition: BM25 rescues a dense miss.

    When dense retrieval ranks the relevant doc low (e.g. it's short and
    lexically distinctive) but BM25 ranks it high, fusion surfaces it.
    """

    def test_bm25_pulls_up_dense_miss(self):
        """Doc 3 has rare exact tokens ('200', 'бюджетных') that BM25 rewards."""
        idx = BM25Index.build(CORPUS)
        # Simulate: dense ranks doc 3 at position 5 (out of top-3)
        dense_ranking = [0, 1, 4, 2, 3]  # doc 3 is 5th
        bm25_hits = idx.search("бюджетных мест 200", top_k=5)
        bm25_ranking = [d for d, _ in bm25_hits]
        # Doc 3 should be top-1 in BM25
        assert bm25_ranking[0] == 3
        # RRF fusion should pull doc 3 into top-3
        fused = fuse_rrf([dense_ranking, bm25_ranking], k=60)
        fused_ids = [d for d, _ in fused]
        assert 3 in fused_ids[:3]
