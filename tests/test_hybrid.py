class TestTokenize:
    def test_lowercase(self):
        assert "программная" in tokenize_ru("Программная ИНЖЕНЕРИЯ")

    def test_strips_markdown(self):
        toks = tokenize_ru("**Проходной** балл — 260")
        assert "проходной" in toks
        assert "260" in toks
        assert "**" not in toks

    def test_stopwords_removed(self):
        toks = tokenize_ru("Где находится главный корпус университета")
        assert "где" not in toks  # stopword
        assert "на" not in toks    # stopword (not in this string but guard)
        assert "корпус" in toks
        assert "университета" in toks

    def test_empty(self):
        assert tokenize_ru("") == []
        assert tokenize_ru("   ") == []

    def test_digits_kept(self):
        toks = tokenize_ru("09.03.04 260 баллов")
        assert "260" in toks
        assert "баллов" in toks


