# A small Russian university corpus for deterministic tests.
CORPUS = [
    "Проходной балл на направление Программная инженерия — 260 баллов.",
    "Проходной балл на Кибербезопасность составляет 262 балла.",
    "Главный корпус МИРЭА находится на улице Стромынка 20.",
    "Бюджетных мест на Информатику и вычислительную технику — 200.",
    "Студенческий городок расположен на проспекте Вернадского.",
]


@pytest.fixture(scope="module")
def idx():
    return BM25Index.build(CORPUS, k1=1.5, b=0.75)


class TestBM25:
    def test_exact_match_top1(self, idx):
        """A query with strong lexical overlap ranks the right doc first."""
        hits = idx.search("проходной балл программная инженерия", top_k=3)
        assert hits[0][0] == 0  # doc 0 is the exact match

    def test_number_match(self, idx):
        """Rare numeric tokens (260) are high-IDF and drive retrieval."""
        hits = idx.search("сколько баллов 260", top_k=3)
        assert hits[0][0] == 0

    def test_different_doc(self, idx):
        hits = idx.search("главный корпус стромынка", top_k=3)
        assert hits[0][0] == 2

    def test_scores_nonnegative(self, idx):
        hits = idx.search("бюджетные места", top_k=5)
        for _, score in hits:
            assert score >= 0.0

    def test_scores_descending(self, idx):
        hits = idx.search("баллов проходной", top_k=5)
        scores = [s for _, s in hits]
        assert scores == sorted(scores, reverse=True)

    def test_oov_query(self, idx):
        """All-out-of-vocabulary query returns empty (no false hits)."""
        hits = idx.search("qwerty zzzz", top_k=3)
        assert hits == []

    def test_empty_query(self, idx):
        assert idx.search("", top_k=3) == []
        assert idx.search([], top_k=3) == []

    def test_top_k_clamped(self, idx):
        """top_k larger than corpus returns all docs."""
        hits = idx.search("баллов", top_k=999)
        assert len(hits) <= idx.n_docs

    def test_save_load_roundtrip(self, idx):
        """Saved and reloaded index produces identical search results."""
        with tempfile.NamedTemporaryFile(suffix=".pkl", delete=False) as f:
            path = f.name
        try:
            idx.save(path)
            idx2 = BM25Index.load(path)
            assert idx2.n_docs == idx.n_docs
            assert len(idx2.inverted) == len(idx.inverted)
            # Same ranking for a probe query
            q = "проходной балл"
            h1 = idx.search(q, top_k=3)
            h2 = idx2.search(q, top_k=3)
            assert [d for d, _ in h1] == [d for d, _ in h2]
            for (_, s1), (_, s2) in zip(h1, h2):
                assert abs(s1 - s2) < 1e-6
        finally:
            os.unlink(path)

    def test_empty_corpus_raises(self):
        with pytest.raises(ValueError):
            BM25Index.build([])


