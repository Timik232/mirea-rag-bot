class TestMinmax:
    def test_basic(self):
        assert _minmax({0: 1.0, 1: 3.0, 2: 5.0}) == {0: 0.0, 1: 0.5, 2: 1.0}

    def test_empty(self):
        assert _minmax({}) == {}

    def test_constant(self):
        # All-equal scores → all mapped to 1.0 (not discarded by threshold)
        assert _minmax({0: 0.5, 1: 0.5}) == {0: 1.0, 1: 1.0}


class TestRRF:
    def test_basic_fusion(self):
        """A doc ranked #1 in both backends scores highest."""
        dense = [10, 20, 30]
        bm25 = [10, 30, 40]
        fused = fuse_rrf([dense, bm25], k=60)
        ids = [d for d, _ in fused]
        assert ids[0] == 10  # rank 1 in both

    def test_scores_in_unit_range(self):
        fused = fuse_rrf([[1, 2, 3], [3, 2, 1]], k=60)
        for _, s in fused:
            assert 0.0 <= s <= 1.0

    def test_weight_bias(self):
        """Higher dense weight → dense-only doc ranks up."""
        dense = [10, 20]   # 10 is dense #1
        bm25 = [20, 10]    # 20 is bm25 #1
        # Equal weights → tie broken by fusion formula
        fused_eq = fuse_rrf([dense, bm25], k=60, weights=[0.5, 0.5])
        # Dense-heavy → 10 should win
        fused_dense = fuse_rrf([dense, bm25], k=60, weights=[0.9, 0.1])
        assert fused_dense[0][0] == 10

    def test_empty(self):
        assert fuse_rrf([], k=60) == []

    def test_weight_validation(self):
        with pytest.raises(ValueError):
            fuse_rrf([[1, 2]], k=60, weights=[0.5, 0.5])


class TestWeighted:
    def test_basic(self):
        dense = [(10, 0.9), (20, 0.5)]
        bm25 = [(10, 5.0), (30, 3.0)]
        fused = fuse_weighted([dense, bm25], weights=[0.5, 0.5])
        ids = [d for d, _ in fused]
        # Doc 10 is top in both → should be #1
        assert ids[0] == 10

    def test_scores_in_unit_range(self):
        dense = [(1, 0.8), (2, 0.3)]
        bm25 = [(2, 5.0), (3, 1.0)]
        fused = fuse_weighted([dense, bm25])
        for _, s in fused:
            assert 0.0 <= s <= 1.0 + 1e-9

    def test_complementarity(self):
        """A doc only in BM25 but with high lexical score surfaces in fusion."""
        dense = [(10, 0.9), (11, 0.8)]
        bm25 = [(20, 100.0), (10, 50.0)]  # doc 20 not in dense at all
        fused = fuse_weighted([dense, bm25], weights=[0.5, 0.5])
        ids = [d for d, _ in fused]
        # Doc 20 should appear (BM25 found it, even though dense missed it)
        assert 20 in ids

    def test_empty(self):
        assert fuse_weighted([]) == []


